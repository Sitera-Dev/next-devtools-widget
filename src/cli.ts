import * as fs from 'node:fs';
import * as path from 'node:path';

export interface InitOptions {
  cwd?: string;
  silent?: boolean;
}

export interface InitResult {
  success: boolean;
  routeCreated: boolean;
  instrumentationCreated: boolean;
  instrumentationUpdated: boolean;
  isTypeScript: boolean;
  hasSrc: boolean;
  appDir: string;
}

const GREEN = '\x1b[32m';
const CYAN = '\x1b[36m';
const YELLOW = '\x1b[33m';
const BOLD = '\x1b[1m';
const RESET = '\x1b[0m';

export function runInit(opts: InitOptions = {}): InitResult {
  const cwd = opts.cwd || process.cwd();
  const log = opts.silent ? () => {} : console.log;

  log(`\n${BOLD}🚀 Setting up next-devtools...${RESET}\n`);

  // 1. Detect TypeScript
  const isTypeScript = fs.existsSync(path.join(cwd, 'tsconfig.json'));
  const tsExt = isTypeScript ? 'ts' : 'js';
  const tsxExt = isTypeScript ? 'tsx' : 'jsx';

  // 2. Detect `src` directory and App Router
  const hasSrc = fs.existsSync(path.join(cwd, 'src', 'app')) || fs.existsSync(path.join(cwd, 'src'));
  const baseDir = hasSrc && fs.existsSync(path.join(cwd, 'src', 'app')) ? path.join(cwd, 'src') : cwd;
  const appDir = path.join(baseDir, 'app');

  let routeCreated = false;
  let instrumentationCreated = false;
  let instrumentationUpdated = false;

  // 3. Create SSE API Route Handler
  const sseDir = path.join(appDir, 'api', 'next-devtools', 'sse');
  const sseFile = path.join(sseDir, `route.${tsExt}`);

  if (!fs.existsSync(sseFile)) {
    fs.mkdirSync(sseDir, { recursive: true });
    const sseContent = `// Auto-generated by next-devtools-widget init\nexport { GET } from 'next-devtools-widget/server/route';\n`;
    fs.writeFileSync(sseFile, sseContent, 'utf8');
    routeCreated = true;
    log(`${GREEN}✓${RESET} Created SSE route handler: ${CYAN}${path.relative(cwd, sseFile)}${RESET}`);
  } else {
    log(`${YELLOW}ℹ${RESET} Route handler already exists: ${CYAN}${path.relative(cwd, sseFile)}${RESET} (skipped)`);
  }

  // 4. Create or update `instrumentation.ts`
  // In Next.js, instrumentation file is located at the root of `src/` or project root.
  const instrFile = path.join(baseDir, `instrumentation.${tsExt}`);
  const instrSnippet = `    const { registerNextDevTools } = await import('next-devtools-widget/server');\n    registerNextDevTools();\n`;

  if (!fs.existsSync(instrFile)) {
    const instrContent = `// Auto-generated by next-devtools-widget init\nexport async function register() {\n  if (process.env.NEXT_RUNTIME === 'nodejs') {\n${instrSnippet}  }\n}\n`;
    fs.writeFileSync(instrFile, instrContent, 'utf8');
    instrumentationCreated = true;
    log(`${GREEN}✓${RESET} Created server instrumentation: ${CYAN}${path.relative(cwd, instrFile)}${RESET}`);
  } else {
    const existing = fs.readFileSync(instrFile, 'utf8');
    if (!existing.includes('registerNextDevTools')) {
      if (/export\s+async\s+function\s+register\s*\([^)]*\)\s*\{/.test(existing)) {
        const updated = existing.replace(
          /(export\s+async\s+function\s+register\s*\([^)]*\)\s*\{)/,
          `$1\n  if (process.env.NEXT_RUNTIME === 'nodejs') {\n${instrSnippet}  }`,
        );
        fs.writeFileSync(instrFile, updated, 'utf8');
        instrumentationUpdated = true;
        log(`${GREEN}✓${RESET} Registered next-devtools in existing: ${CYAN}${path.relative(cwd, instrFile)}${RESET}`);
      } else {
        log(`${YELLOW}ℹ${RESET} Found ${CYAN}${path.relative(cwd, instrFile)}${RESET}. Please ensure ${BOLD}registerNextDevTools()${RESET} is called inside register().`);
      }
    } else {
      log(`${YELLOW}ℹ${RESET} Server instrumentation already configured in: ${CYAN}${path.relative(cwd, instrFile)}${RESET}`);
    }
  }

  // 5. Check layout
  const layoutFile = path.join(appDir, `layout.${tsxExt}`);
  const layoutExists = fs.existsSync(layoutFile);
  let layoutHasWidget = false;
  if (layoutExists) {
    const layoutContent = fs.readFileSync(layoutFile, 'utf8');
    layoutHasWidget = layoutContent.includes('NextDevTools');
  }

  log(`\n${GREEN}${BOLD}Setup completed successfully! 🎉${RESET}\n`);

  if (!layoutHasWidget) {
    log(`${BOLD}Final Step:${RESET} Mount ${CYAN}<NextDevTools />${RESET} in your root layout:`);
    log(`\nFile: ${CYAN}${path.relative(cwd, layoutExists ? layoutFile : path.join(appDir, `layout.${tsxExt}`))}${RESET}`);
    log(`-----------------------------------------------------------------`);
    log(`import { NextDevTools } from 'next-devtools-widget';\n`);
    log(`export default function RootLayout({ children }: { children: React.ReactNode }) {`);
    log(`  return (`);
    log(`    <html lang="en">`);
    log(`      <body>`);
    log(`        {children}`);
    log(`        {process.env.NODE_ENV === 'development' && <NextDevTools />}`);
    log(`      </body>`);
    log(`    </html>`);
    log(`  );`);
    log(`}`);
    log(`-----------------------------------------------------------------\n`);
  } else {
    log(`${GREEN}✓${RESET} <NextDevTools /> already detected in root layout.\n`);
  }

  return {
    success: true,
    routeCreated,
    instrumentationCreated,
    instrumentationUpdated,
    isTypeScript,
    hasSrc,
    appDir,
  };
}

// Direct invocation via CLI
if (require.main === module || (typeof process.argv[1] === 'string' && process.argv[1].endsWith('cli.js'))) {
  const args = process.argv.slice(2);
  const command = args[0] || 'init';

  if (command === '--help' || command === '-h' || (command !== 'init' && !command.startsWith('-'))) {
    console.log(`\n${BOLD}next-devtools-widget CLI${RESET}`);
    console.log(`\nUsage:`);
    console.log(`  npx next-devtools-widget init     Set up SSE route handler and server instrumentation`);
    console.log(`  npx next-devtools-widget --help   Show this help message\n`);
    process.exit(0);
  }

  try {
    runInit();
  } catch (err) {
    console.error(`\x1b[31mError during setup:\x1b[0m`, (err as Error)?.message || err);
    process.exit(1);
  }
}
